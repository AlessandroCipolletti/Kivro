import { test, expect } from "@playwright/test";
import { register } from "./auth";
import { noOverflow, uiFixtureSession } from "./ui-fixtures";
import { defaultWorkerPermissions } from "../src/lib/worker-policy";
import { sellerCapabilityFixture } from "../tests/support/seller-capabilities";
import type { SellerCapability } from "../src/lib/types";

test("real seller capacity saves only changed limits and requires explicit stale revision reload without new drafts", async ({ page }, info) => {
  const account = await register(page, "capacity");
  const config = await (await page.request.get("/api/config")).json();
  const permissions = defaultWorkerPermissions(); permissions.inference.model = "synthetic-capacity-browser-fixture";
  const created = await page.request.post("/api/seller/capabilities", { headers: account.headers, data: { title: "Capacity browser verification", summary: "Synthetic private capacity settings acceptance.", description: "Never execute this unpublished acceptance capability.", category: config.categories[0], tags: [], priceTierId: config.priceTiers[0].id, permissions, internalInstructions: "No live execution.", dependencies: [], examples: [], estimatedDurationSeconds: 60, ioContract: { schemaVersion: 1, inputs: [], output: { type: "TEXT", description: "Text", required: true } } } });
  expect(created.status(), await created.text()).toBe(200);
  const first = await created.json() as SellerCapability;
  const writes: unknown[] = [];
  await page.route(`**/api/seller/capabilities/${first.id}`, route => { if (route.request().method() === "PUT") writes.push(route.request().postDataJSON()); return route.continue(); });
  expect((await page.goto("/selling/capabilities"))?.status()).toBe(200);
  await page.getByRole("button", { name: `Capacity ${first.title}`, exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("button", { name: "Save capacity", exact: true })).toBeDisabled();
  await dialog.getByLabel("Maximum concurrent jobs").fill("2");
  await dialog.getByLabel("Maximum queued jobs").fill("0");
  await dialog.getByLabel("Maximum scheduled jobs").fill("0");
  await expect(dialog).toContainText("do not cancel work, alter payments or create a capability version");
  await dialog.getByRole("button", { name: "Save capacity", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(writes).toEqual([{ concurrency: 2, maxQueue: 0, maxScheduled: 0, expectedRevision: first.lifecycleRevision }]);
  const load = async () => (await (await page.request.get("/api/seller/capabilities")).json() as SellerCapability[]).find(cap => cap.id === first.id)!;
  const second = await load();
  expect(second.versionId).toBe(first.versionId); expect(second.version).toBe(first.version);
  expect(second.lifecycleRevision).toBe(first.lifecycleRevision! + 1);
  await page.getByRole("button", { name: `Capacity ${first.title}`, exact: true }).click();
  const concurrent = await page.request.put(`/api/seller/capabilities/${first.id}`, { headers: account.headers, data: { concurrency: 3, expectedRevision: second.lifecycleRevision } });
  expect(concurrent.status(), await concurrent.text()).toBe(200);
  const third = await concurrent.json() as SellerCapability;
  await dialog.getByLabel("Maximum queued jobs").fill("1");
  await dialog.getByRole("button", { name: "Save capacity", exact: true }).click();
  await expect(dialog.getByText(/Settings changed elsewhere/)).toBeVisible();
  await expect(dialog.getByLabel("Maximum queued jobs")).toHaveValue("1");
  await expect(dialog.getByRole("button", { name: "Save capacity", exact: true })).toBeDisabled();
  expect(writes).toHaveLength(2);
  await noOverflow(page);
  await page.screenshot({ path: `apps/web/verification/capacity-conflict-${info.project.name}.png`, fullPage: true });
  await dialog.getByRole("button", { name: "Reload latest settings", exact: true }).click();
  await expect(dialog.getByLabel("Maximum concurrent jobs")).toHaveValue("3");
  await expect(dialog.getByLabel("Maximum queued jobs")).toHaveValue("0");
  expect(writes).toHaveLength(2);
  await dialog.getByLabel("Maximum queued jobs").fill("1");
  await dialog.getByRole("button", { name: "Save capacity", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(writes.at(-1)).toEqual({ maxQueue: 1, expectedRevision: third.lifecycleRevision });
  const final = await load();
  expect(final).toMatchObject({ concurrency: 3, maxQueue: 1, maxScheduled: 0, versionId: first.versionId, version: first.version, visibility: "DRAFT" });
});

test("capacity incomplete wire snapshots fail closed and numeric validation is associated without requests", async ({ page }, info) => {
  await uiFixtureSession(page);
  let cap: SellerCapability = sellerCapabilityFixture({ title: "Capacity missing snapshot", visibility: "DRAFT" });
  delete cap.concurrency;
  let failure = false, writes = 0;
  await page.route("**/api/seller/capabilities", route => failure ? route.fulfill({ status: 503, json: { error: { code: "TEMPORARY", message: "Capacity snapshot unavailable" } } }) : route.fulfill({ json: [cap] }));
  await page.route(`**/api/seller/capabilities/${cap.id}`, route => { writes++; return route.fulfill({ status: 500, json: { error: { code: "UNEXPECTED", message: "Unexpected mutation" } } }); });
  await page.goto("/selling/capabilities");
  await expect(page.getByRole("alert").filter({ hasText: "The service returned an invalid response" })).toBeVisible();
  await expect(page.getByRole("button", { name: `Capacity ${cap.title}`, exact: true })).toHaveCount(0);
  failure = true;
  await page.getByRole("button", { name: "Try again", exact: true }).click();
  await expect(page.getByText("Capacity snapshot unavailable", { exact: true })).toBeVisible();
  failure = false; cap = { ...cap, concurrency: 1, maxQueue: 3, maxScheduled: 20, lifecycleRevision: 0 };
  await page.getByRole("button", { name: "Try again", exact: true }).click();
  await page.getByRole("button", { name: `Capacity ${cap.title}`, exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByLabel("Maximum concurrent jobs")).toBeEnabled();
  await dialog.getByLabel("Maximum concurrent jobs").fill("5");
  await dialog.getByRole("button", { name: "Save capacity", exact: true }).click();
  await expect(dialog.getByLabel("Maximum concurrent jobs")).toHaveAttribute("aria-invalid", "true");
  await expect(dialog.getByLabel("Maximum concurrent jobs")).toHaveAttribute("aria-describedby", /help$/);
  await expect(dialog.getByLabel("Maximum queued jobs")).toHaveAttribute("aria-invalid", "false");
  expect(writes).toBe(0);
  await noOverflow(page);
  await page.screenshot({ path: `apps/web/verification/capacity-validation-${info.project.name}.png`, fullPage: true });
});
