import { test, expect } from "@playwright/test";
import { register } from "./auth";
import { defaultWorkerPermissions } from "../src/lib/worker-policy";

test("real immutable draft history, exact diff, validation reset and retirement", async ({ page }, info) => {
  const account = await register(page, "versions");
  const config = await (await page.request.get("/api/config")).json();
  const permissions = defaultWorkerPermissions();
  permissions.inference.model = "synthetic-browser-fixture";
  const body = { title: "Version workflow verification", summary: "Original immutable draft summary.", description: "Synthetic unpublished capability created by browser acceptance.", category: config.categories[0], tags: [], priceTierId: config.priceTiers[0].id, internalInstructions: "Never execute this private acceptance draft.", estimatedDurationSeconds: 60, permissions, dependencies: [], examples: [], ioContract: { schemaVersion: 1, inputs: [], output: { type: "TEXT", description: "Text result", required: true } }, schedule: { mode: "ALWAYS", timezone: "UTC", windows: [], overrides: [] } };
  const created = await page.request.post("/api/seller/capabilities", { headers: account.headers, data: body });
  expect(created.status(), await created.text()).toBe(200);
  const first = await created.json();
  const edited = await page.request.put(`/api/seller/capabilities/${first.id}`, { headers: account.headers, data: { ...body, summary: "Revised immutable draft summary.", expectedRevision: first.lifecycleRevision } });
  expect(edited.status(), await edited.text()).toBe(200);
  const second = await edited.json();
  expect(first.versionId).not.toBe(second.versionId);
  expect((await page.goto(`/selling/capabilities/${first.id}/versions`))?.status()).toBe(200);
  await expect(page.getByRole("heading", { name: "Capability versions", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Make version 2 active" })).toBeDisabled();
  await page.getByLabel("Compare with", { exact: true }).selectOption(first.versionId);
  await page.locator(".version-diff-category").filter({ hasText: "Metadata" }).locator("summary").click();
  await expect(page.locator(".version-comparison").getByText(body.summary, { exact: true })).toBeVisible();
  await expect(page.locator(".version-comparison").getByText("Revised immutable draft summary.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Start new validation", exact: true }).click();
  await expect(page.getByRole("dialog")).toContainText("does not execute the worker self-test");
  await page.getByRole("dialog").getByRole("button", { name: "Start new validation", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Make version 2 active" })).toBeDisabled();
  await page.getByRole("navigation", { name: "Capability version history" }).getByRole("button", { name: /^Version 1/ }).click();
  await page.getByRole("button", { name: "Retire version", exact: true }).click();
  await page.getByRole("dialog").getByLabel("Reason", { exact: true }).fill("Retire the superseded acceptance draft.");
  await page.getByRole("dialog").getByRole("button", { name: "Retire version", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Retire version", exact: true })).toBeDisabled();
  const historical = await (await page.request.get(`/api/seller/capabilities/${first.id}/versions/${first.versionId}`)).json();
  expect(historical.summary).toBe(body.summary); expect(historical.state).toBe("RETIRED");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `apps/web/verification/versions-${info.project.name}.png`, fullPage: true });
});
