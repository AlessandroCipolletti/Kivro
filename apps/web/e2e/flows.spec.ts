  await expect(page.getByLabel("Monday end 1")).toHaveValue("07:00");
  await page.getByText("Date overrides", { exact: true }).click();
  await page.getByRole("button", { name: "Add date override" }).click();
  await page.getByLabel("Date for override 1").fill("2030-06-12");
  await page.getByLabel("Override 1 availability").selectOption("TIMED");
  await page.getByLabel("Override 1 start").fill("20:15");
  await page.getByLabel("Override 1 end").fill("03:45");
