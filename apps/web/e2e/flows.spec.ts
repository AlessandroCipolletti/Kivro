  expect(submitted.permissions.network).toEqual({ mode: "RESEARCH", allowedDomains: ["example.com"], researchLimits: { maxQueries: 0, maxPages: 1, maxTotalBytes: 2048 } });
  expect(submitted.schedule.overrides).toEqual([{ date: "2030-06-12", available: true, start: "20:15", end: "03:45" }]);
