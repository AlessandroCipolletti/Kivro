import { test, expect, type Page } from "@playwright/test";
import type { CapabilityDTO } from "@kivro/contracts";
import { register } from "./auth";

async function visit(page: Page, path: string, title: string | RegExp) {
  const response = await page.goto(path);
  expect(response?.status(), `${path} must not be a framework 404`).toBe(200);
  await expect(page.locator("main h1")).toHaveText(title);
  await expect(page.getByText("Loading", { exact: true })).toHaveCount(0);
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
}

test("real catalog, detail, mobile brand and buyer upload", async ({ page }, info) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await visit(page, "/", "Find the right capability.");
  await expect(page.locator(".results-caption")).not.toContainText("Finding");
  const brand = info.project.name === "mobile" ? page.locator(".topbar .mobile-brand") : page.locator(".sidebar .brand");
  await expect(brand).toBeInViewport();
  await noOverflow(page);
  await page.screenshot({ path: `apps/web/verification/marketplace-${info.project.name}.png`, fullPage: true });
  await page.getByRole("textbox", { name: "Search capabilities" }).fill("no-capability-with-this-exact-name");
  await expect(page.getByRole("heading", { name: "No capabilities found" })).toBeVisible();
  await page.getByRole("button", { name: "Clear search" }).click();
  await register(page, "upload");
  const response = await page.request.get("/api/capabilities");
  expect(response.ok()).toBe(true);
  const capabilities = await response.json() as CapabilityDTO[];
  const cap = capabilities.find(item => item.ioContract.inputs.some(field => field.constraints?.allowedExtensions?.includes(".txt")));
  test.skip(!cap, "Live catalog has no capability accepting a .txt upload.");
  await visit(page, `/capabilities/${cap!.id}`, cap!.title);
  const field = cap!.ioContract.inputs.find(input => input.constraints?.allowedExtensions?.includes(".txt"))!;
  await page.getByLabel(field.label, { exact: false }).setInputFiles({ name: "web-verification.txt", mimeType: "text/plain", buffer: Buffer.from("A real upload from the web verification suite.\n") });
  await expect(page.getByText("web-verification.txt", { exact: true })).toBeVisible();
  const text = cap!.ioContract.inputs.find(input => input.type === "LONG_TEXT");
  if (text) await page.getByLabel(text.label, { exact: false }).fill("Buyer-entered text remains editable while a capability is offline.");
  if (!cap!.availability.canRunNow && cap!.availability.status !== "SCHEDULED_OFFLINE") await expect(page.getByRole("button", { name: "Currently unavailable" })).toBeDisabled();
  await noOverflow(page);
  await page.screenshot({ path: `apps/web/verification/detail-${info.project.name}.png`, fullPage: true });
  expect(errors).toEqual([]);
});

test("settings creates and revokes a scoped key; admin remains role-gated", async ({ page }, info) => {
  await register(page, "settings");
  await visit(page, "/settings", "Settings");
  await expect(page.getByRole("heading", { name: "No API keys" })).toBeVisible();
  await page.getByRole("button", { name: "Create key", exact: true }).click();
  await page.getByRole("dialog").getByRole("textbox", { name: "Name", exact: true }).fill("Verification key");
  const created = page.waitForResponse(response => response.url().endsWith("/api/api-keys") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Create API key", exact: true }).click();
  expect((await created).status()).toBe(200);
  await expect(page.getByRole("dialog").locator(".secret-once")).not.toBeEmpty();
  await page.getByRole("dialog").getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("button", { name: "Revoke Verification key" }).click();
  await page.getByRole("button", { name: "Revoke key", exact: true }).click();
  await expect(page.getByText("Revoked", { exact: true })).toBeVisible();
  await noOverflow(page);
  await page.screenshot({ path: `apps/web/verification/settings-${info.project.name}.png`, fullPage: true });
  expect((await page.goto("/admin"))?.status()).toBe(200);
  await expect(page.getByText("This page is restricted to platform administrators.")).toBeVisible();
});

